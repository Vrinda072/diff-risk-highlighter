// What does each detector contribute? Measured on the DEVELOPMENT fixtures
// (never the held-out set): each signal is switched off in turn, and also run
// on its own, against the hunks labelled as the real fix.
//
//   node eval/ablation.js            print the report
//   node eval/ablation.js --write    also save it as docs/ablation.md
//
// test/ablation.test.js fails if the saved report no longer matches.

const fs = require('node:fs');
const path = require('node:path');
const engine = require('../src/risk-engine.js');
const { parseDiff } = require('../test/helpers/parse-diff.js');

const ROOT = path.resolve(__dirname, '..');
const DIR = path.join(ROOT, 'test', 'fixtures', 'real-prs');
const REPORT = path.join(ROOT, 'docs', 'ablation.md');

const NAMES = {
  sql: 'SQL built from strings',
  boundary: 'Off-by-one shape',
  'error-handling': 'Removed error handling',
  security: 'Security keywords',
  condition: 'Removed or changed condition',
  concurrency: 'Locking and check-then-act',
  'weakened-test': 'Weakened test',
  'security-in-test': 'Security keyword in a test',
  signature: 'Signature change',
  'large-hunk': 'Large hunk (fallback)',
};

function loadHunks() {
  const metadata = JSON.parse(fs.readFileSync(path.join(DIR, 'metadata.json'), 'utf8'));
  return metadata.flatMap((entry) => {
    const matches = (list, h) =>
      (list || []).some((f) => f.file === h.filePath && Number(f.header.match(/\+(\d+)/)[1]) === h.newStart);
    return parseDiff(fs.readFileSync(path.join(DIR, entry.fixture), 'utf8')).map((hunk) => ({
      hunk,
      fix: matches(entry.fixHunks, hunk),
      expected: matches(entry.expectedFlags, hunk),
    }));
  });
}

function measure(rows, disable) {
  const total = { fixes: 0, fixesFlagged: 0, flagged: 0, otherFlagged: 0, otherHigh: 0 };
  for (const row of rows) {
    const { level } = engine.assessHunk(row.hunk, { disable });
    const flagged = level !== 'low';
    if (flagged) total.flagged++;
    if (row.fix) {
      total.fixes++;
      if (flagged) total.fixesFlagged++;
    } else {
      if (flagged) total.otherFlagged++;
      if (level === 'high' && !row.expected) total.otherHigh++;
    }
  }
  return total;
}

function ablate(rows = loadHunks()) {
  const full = measure(rows, []);
  const detectors = engine.DETECTOR_IDS.map((id) => ({
    id,
    // alone: every other detector off, shortcuts still on
    alone: measure(rows, engine.DETECTOR_IDS.filter((other) => other !== id)),
    without: measure(rows, [id]),
  }));
  const shortcuts = engine.SHORTCUT_IDS.map((id) => ({ id, without: measure(rows, [id]) }));
  return { hunks: rows.length, full, detectors, shortcuts };
}

const signed = (n) => (n > 0 ? `+${n}` : `${n}`);
const share = (part, whole) => (whole ? `${Math.round((100 * part) / whole)}%` : 'n/a');

function render({ hunks, full, detectors, shortcuts }) {
  const lines = [
    '# What each detector contributes',
    '',
    'Generated by `node eval/ablation.js --write`. **Development set only**: the 42 pull',
    'requests in `test/fixtures/real-prs/`, which also shaped the heuristics, so none of',
    'this predicts performance on new code. "Fix hunks" are the ones labelled as the real',
    'fix. A flagged hunk that is not a fix is not necessarily wrong: it can still be',
    'worth reading.',
    '',
    `All signals on: ${full.fixesFlagged} of ${full.fixes} fix hunks flagged, ${full.flagged} of ${hunks} hunks flagged, ` +
      `${full.otherHigh} non-fix hunks flagged high.`,
    '',
    '## Detectors',
    '',
    '"Alone" runs only that detector. "Without it" shows what changes when only it is off.',
    '',
    '| Detector | Alone: flags | Alone: fix hunks | Alone: share that are fixes | Without it: fix hunks | Without it: other flags | Without it: non-fix high |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const d of detectors) {
    lines.push(
      `| ${NAMES[d.id]} | ${d.alone.flagged} | ${d.alone.fixesFlagged} | ${share(d.alone.fixesFlagged, d.alone.flagged)} | ` +
        `${signed(d.without.fixesFlagged - full.fixesFlagged)} | ${signed(d.without.otherFlagged - full.otherFlagged)} | ` +
        `${signed(d.without.otherHigh - full.otherHigh)} |`
    );
  }
  lines.push(
    '',
    `For scale, ${share(full.fixes, hunks)} of all hunks are fix hunks, so a detector picking hunks at random would score that.`,
    '',
    '## Shortcuts',
    '',
    'What changes when a "harmless" shortcut is off. A shortcut that hid a fix would show',
    'a positive number in the first column.',
    '',
    '| Shortcut off | Fix hunks flagged | Other flags | Non-fix high |',
    '|---|---|---|---|'
  );
  for (const s of shortcuts) {
    lines.push(
      `| ${s.id} | ${signed(s.without.fixesFlagged - full.fixesFlagged)} | ${signed(s.without.otherFlagged - full.otherFlagged)} | ` +
        `${signed(s.without.otherHigh - full.otherHigh)} |`
    );
  }
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  const text = render(ablate());
  console.log(text);
  if (process.argv.includes('--write')) fs.writeFileSync(REPORT, text);
}

module.exports = { ablate, render, loadHunks, measure, REPORT };
